/**
 * Work and power for class 9.
 *
 * A force does work when the thing it acts on moves: W = F × s, in joules
 * (1 J = 1 N × 1 m). Against the motion — friction on a sliding box — the work
 * is negative. At right angles to the motion — the upward force on a bag
 * carried along a level road — it is zero, and so it is when nothing moves at
 * all, however hard you push. Lifting a mass m through a height h takes
 * W = m g h. Power is how fast the work is done, P = W ÷ t, in watts; two
 * climbers going up the same stairs do the same work, but the faster one has
 * more power. The electricity bill counts energy in kilowatt hours:
 * 1 kWh = 3.6 × 10⁶ J, one "unit".
 *
 * Simplifications: the force is steady; a load is lifted at a steady speed, so
 * the lifting force equals its weight; g = 9.8 m/s²; P = W ÷ t is the average
 * power over the whole climb.
 */
