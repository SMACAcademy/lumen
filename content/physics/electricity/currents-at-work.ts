/**
 * Effects of electric current (class 7) and magnetic effects of current
 * (class 10), in seven small scenes.
 *
 * A current heats the wire it flows through: H = I²Rt. That is how a heater,
 * an iron and a bulb's filament work, and how a fuse protects a house: its
 * thin wire melts when the current is more than its rating. India's mains is
 * 220 V at 50 Hz; overloading and short circuits draw too much current, and
 * an earth wire keeps a metal case safe.
 *
 * A current also makes a magnetic field. A coil round an iron nail becomes an
 * electromagnet, stronger for more turns and more current. Field lines run
 * from N to S round a bar magnet and never cross; round a straight wire they
 * are circles (right-hand thumb rule); a solenoid behaves like a bar magnet.
 * A current in a field is pushed (Fleming's left-hand rule), which turns a
 * motor; moving a magnet in a coil makes a current, which a generator uses.
 *
 * Simplifications: a fuse melts at once when the current passes its rating;
 * the house wiring is taken to be 0.5 Ω, so a short circuit draws 440 A; the
 * iron core makes the electromagnet 100 times stronger and each pin needs a
 * strength of 20; the galvanometer moves one division per 20 turns × m/s; the
 * motor and generator are drawn turning at most once a second.
 */
