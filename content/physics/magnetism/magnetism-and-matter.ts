/**
 * Magnetism and matter for class 12 (NCERT chapter 5).
 *
 * A bar magnet is a magnetic dipole: its far field falls as 1/r³ and is
 * twice as strong on the axis as on the equator. Its field lines close on
 * themselves, because there are no magnetic monopoles (Gauss's law for
 * magnetism). In a uniform field it feels a torque mB sin θ, has energy
 * −mB cos θ, and swings with period 2π√(I/mB). The Earth's field at a place
 * is fixed by its size, its dip and its declination. Inside matter,
 * B = μ₀(H + M) with M = χH: diamagnets have small negative χ, paramagnets
 * small positive χ that falls as 1/T, ferromagnets a huge χ — and a
 * hysteresis loop whose retentivity and coercivity decide whether the
 * material makes a good electromagnet core or a good permanent magnet.
 *
 * Simplifications, said plainly in the text below: the dipole formulas are
 * the short-magnet ones (r much larger than the magnet); the Earth's values
 * are rounded present-day figures; the ferromagnet's M(H) and the hysteresis
 * loop are smooth model shapes with typical values, not measured curves.
 */
