/**
 * Electrostatic potential and capacitance, class 12 (NCERT chapter 2).
 *
 * The potential at a point is the work done per unit charge by an outside
 * agent bringing a test charge there from far away: V = kq/r for a point
 * charge, and potentials simply add. Equipotentials cross field lines at
 * right angles, and moving along one costs no work. A pair of charges stores
 * U = kq₁q₂/r. Inside a conductor the field is zero. A parallel-plate
 * capacitor has C = ε₀KA/d, holds Q = CV and stores U = ½CV²; capacitors
 * combine in series and in parallel, and a charged one shares its charge with
 * an empty one, losing energy as it does.
 *
 * Simplifications, said plainly: point charges are small balls (distances
 * are never taken below 0.5 cm); the conducting sphere sits in a steady
 * outside field of 5 kV/m and its potential is measured from the plane
 * through its centre rather than from infinity; the dielectric always fills
 * the whole gap; the plates are wide compared with the gap (no fringing).
 * Energies are given in µJ (microjoules).
 */
