const minus = (n: number) => (n < 0 ? `−${-n}` : String(n));
/** A rational card, written as a book would: "−3/4", "1/(−2)". */
const rational = (p: number, q: number) => ({
  id: `r${p < 0 ? "m" : ""}${Math.abs(p)}-${q < 0 ? "m" : ""}${Math.abs(q)}`,
  label: q < 0 ? `${minus(p)}/(${minus(q)})` : `${minus(p)}/${q}`,
  given: { p, q },
});

