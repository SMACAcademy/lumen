export function resolveModel(id: string): AnySimulationModel {
  const model = modelRegistry[id];
  if (!model) throw new Error(`No simulation model registered for "${id}"`);
  return model;
}

export function resolveRenderer(id: string): AnySimulationRenderer {
  const renderer = rendererRegistry[id];
  if (!renderer) throw new Error(`No renderer registered for "${id}"`);
  return renderer;
}
